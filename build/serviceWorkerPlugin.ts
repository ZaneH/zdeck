import { createHash } from "node:crypto";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import process from "node:process";
import type { Plugin } from "vite";

export const CACHE_PREFIX = "deck-shell-";

// Exact static shell files copied from public/. No wildcards.
export const SHELL_FILES = [
  "index.html",
  "manifest.webmanifest",
  "icons/icon-192.png",
  "icons/icon-512.png",
  "icons/apple-touch-icon.png",
  "icons/favicon-32.png",
] as const;

export function collectPrecache(outDir: string): string[] {
  const urls = SHELL_FILES.filter((file) => existsSync(join(outDir, file))).map(
    (file) => `/${file}`,
  );

  const assetsDir = join(outDir, "assets");
  if (existsSync(assetsDir)) {
    for (const name of readdirSync(assetsDir).sort()) {
      urls.push(`/assets/${name}`);
    }
  }
  return urls;
}

export function computeVersion(outDir: string, precache: string[], marker = ""): string {
  const hash = createHash("sha256");
  hash.update(marker);
  for (const url of precache) {
    hash.update(url);
    const abs = join(outDir, url.slice(1));
    if (existsSync(abs)) hash.update(readFileSync(abs));
  }
  return hash.digest("hex").slice(0, 16);
}

// The worker is intentionally dependency-free. It precaches one exact asset list into
// a cache named for the build, then waits for the user to apply the update.
export function renderServiceWorker(version: string, precache: string[]): string {
  return `// Generated by build/serviceWorkerPlugin.ts at build time. Do not edit.
const CACHE_PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const CACHE = CACHE_PREFIX + ${JSON.stringify(version)};
const PRECACHE = ${JSON.stringify(precache)};
const PRECACHE_SET = new Set(PRECACHE);
const NAVIGATION_PATHS = new Set(["/", "/index.html"]);

self.addEventListener("install", (event) => {
  // Install into this build's own cache and wait; the active build stays coherent.
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(
        keys
          .filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE)
          .map((key) => caches.delete(key)),
      );
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // Query variants and anything not in the exact precache list are never handled.
  if (url.search) return;

  if (request.mode === "navigate") {
    if (!NAVIGATION_PATHS.has(url.pathname)) return;
    event.respondWith(
      (async () => {
        const cache = await caches.open(CACHE);
        return (await cache.match("/index.html")) || fetch(request);
      })(),
    );
    return;
  }

  if (!PRECACHE_SET.has(url.pathname)) return;
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      return (await cache.match(url.pathname)) || fetch(request);
    })(),
  );
});
`;
}

export function serviceWorkerPlugin(): Plugin {
  let outDir = "dist";
  return {
    name: "deck-service-worker",
    apply: "build",
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      const marker = process.env.VITE_BUILD_MARKER ?? "";
      const precache = collectPrecache(outDir);
      const version = computeVersion(outDir, precache, marker);
      writeFileSync(join(outDir, "sw.js"), renderServiceWorker(version, precache));
    },
  };
}
